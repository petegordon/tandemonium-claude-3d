"""Game data for the colourways: per pair, per colourway, per seat -> {glTF material name: remap params}, computed on
the delivered rider GLBs (the game's own packed textures) with scripts/recolour.py.

  blender -b --factory-startup --python scripts/colourway_params.py -- [--out out/delivery/goose_colourways.json]
      [--js ../tandemonium/js/goose-colourways-data.js]
"""
import json
import sys
from pathlib import Path

import bpy

argv = sys.argv[sys.argv.index("--") + 1:] if "--" in sys.argv else []
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(Path(__file__).resolve().parent))
import recolour  # noqa: E402


def opt(name, default):
    return argv[argv.index(name) + 1] if name in argv else default


# the game's Goose Outfits pairs (tandemonium js/goose-outfits.js) -> delivered rider files
FILES = {"victorian": {"captain": "goose_captain", "stoker": "goose_stoker_victorian"},
         "cyclists": {"captain": "goose_captain_cyclist", "stoker": "goose_stoker_cyclist"},
         "fancy": {"captain": "goose_captain_fancy", "stoker": "goose_stoker"},
         "georgian": {"captain": "goose_captain_georgian", "stoker": "goose_stoker_georgian"}}
W = json.loads((ROOT / "refs" / "colourways.json").read_text(encoding="utf-8"))
data = {}
for pk, p in W["pairs"].items():
    ways = [{"key": "default", "label": "Original"}]
    for wk, w in p["ways"].items():
        ways.append({"key": wk, "label": w["label"]})
    for seat in ("captain", "stoker"):
        bpy.ops.wm.read_factory_settings(use_empty=True)
        bpy.ops.import_scene.gltf(filepath=str(ROOT / "out" / "delivery" / f"{FILES[pk][seat]}.glb"))
        meshes = [o for o in bpy.data.objects if o.type == "MESH"]
        for wd in ways[1:]:
            wd[seat.capitalize()] = recolour.recolour_objects(meshes, recolour.way_targets(W, wd["key"], seat),
                                                              log=lambda *a: None)
            for v in wd[seat.capitalize()].values():
                v.pop("mean", None)
    data[pk] = {"label": p["label"], "ways": ways}
    print("PAIR", pk, [(w["key"], len(w.get("Captain", {})), len(w.get("Stoker", {}))) for w in ways])
out = ROOT / opt("--out", "out/delivery/goose_colourways.json")
out.write_text(json.dumps(data, indent=1) + "\n", encoding="utf-8")
js = opt("--js", "")
if js:
    Path(js).write_bytes(("// GENERATED by tandemonium-claude-3d scripts/colourway_params.py from refs/colourways.json and the\n"
                          "// delivered rider GLBs -- do not edit by hand. Per Goose Outfits pair: colourways, each with per-seat\n"
                          "// {glTF material name: {hsv: [hue, sat, val]} | {color: [r, g, b] linear}} (js/goose-colourways.js).\n"
                          "export default " + json.dumps(data, indent=1) + ";\n").replace("\n", "\r\n").encode("utf-8"))
print("PARAMS", out, js)
